"""Small media files made once with outside encoders, kept here as bytes.

The EPUB 3.4 core media types sets need an AVIF and a JPEG XL image and MP4
audio with Opus and with AAC. Writing those encoders here is out of reach,
so each file was made once from a generated 16x16 gray PNG (value 128) or
0.5 s of mono silence at 48 kHz, and its bytes are below in base64. A build
reads them from here, so the books stay byte for byte reproducible and need
no encoder. Each function checks the SHA-256 of what it returns.

Made on 2026-11-28 with:

    avifenc 1.4.2 (aom 3.15.2):  avifenc -q 50 -s 10 --ignore-exif --ignore-xmp gray.png gray.avif
    cjxl 0.11.2:                 cjxl gray.png gray.jxl -d 1
    ffmpeg 8.1, Opus:            ffmpeg -f lavfi -i anullsrc=r=48000:cl=mono -t 0.5 -c:a libopus -b:a 6k
                                   -map_metadata -1 -fflags +bitexact -flags:a +bitexact -movflags +faststart opus.mp4
    ffmpeg 8.1, AAC LC:          ffmpeg -f lavfi -i anullsrc=r=48000:cl=mono -t 0.5 -c:a aac -b:a 16k
                                   -map_metadata -1 -fflags +bitexact -flags:a +bitexact -movflags +faststart aac.mp4
"""

from __future__ import annotations

import base64
import hashlib


def _bytes(data: str, sha256: str) -> bytes:
    out = base64.b64decode(data)
    assert hashlib.sha256(out).hexdigest() == sha256, "embedded media changed"
    return out


